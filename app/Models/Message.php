<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class Message extends Model
{
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | DIRECT CHAT
        |--------------------------------------------------------------------------
        */

        'sender_id',
        'receiver_id',

        /*
        |--------------------------------------------------------------------------
        | GROUP CHAT
        |--------------------------------------------------------------------------
        */

        'chat_group_id',

        /*
        |--------------------------------------------------------------------------
        | MESSAGE CONTENT
        |--------------------------------------------------------------------------
        */

        'message',
        'file',

        /*
        |--------------------------------------------------------------------------
        | DELIVERY / READ STATUS
        |--------------------------------------------------------------------------
        */

        'is_read',
        'is_delivered',

        'read_at',
        'delivered_at',

        /*
        |--------------------------------------------------------------------------
        | EDITING
        |--------------------------------------------------------------------------
        */

        'edited_at',

    ];


    protected $casts = [

        /*
        |--------------------------------------------------------------------------
        | STATUS
        |--------------------------------------------------------------------------
        */

        'is_read' => 'boolean',
        'is_delivered' => 'boolean',

        /*
        |--------------------------------------------------------------------------
        | TIMESTAMPS
        |--------------------------------------------------------------------------
        */

        'read_at' => 'datetime',
        'delivered_at' => 'datetime',
        'edited_at' => 'datetime',

    ];


    /*
    |--------------------------------------------------------------------------
    | SENDER
    |--------------------------------------------------------------------------
    */

    public function sender()
    {
        return $this->belongsTo(
            User::class,
            'sender_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | DIRECT RECEIVER
    |--------------------------------------------------------------------------
    */

    public function receiver()
    {
        return $this->belongsTo(
            User::class,
            'receiver_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | GROUP
    |--------------------------------------------------------------------------
    */

    public function group()
    {
        return $this->belongsTo(
            ChatGroup::class,
            'chat_group_id'
        );
    }
}